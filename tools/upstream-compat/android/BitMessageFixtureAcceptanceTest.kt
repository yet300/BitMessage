package com.bitchat.android.protocol

import com.bitchat.android.model.IdentityAnnouncement
import org.junit.Assert.assertNotNull
import org.junit.Test

class BitMessageFixtureAcceptanceTest {
    @Test
    fun acceptsPinnedAppleOuterPacketsAndAnnouncements() {
        listOf(
            "010203010203040506070800000200112233445566774142",
            "010203010203040506070801000200112233445566778899aabbccddeeff4142",
            "0202030102030405060708000000000200112233445566774142",
            "0202030102030405060708010000000200112233445566778899aabbccddeeff4142",
            "0202030102030405060708090000000200112233445566778899aabbccddeeff0200112233445566778899aabbccddeeff4142",
        ).forEach { assertNotNull(BinaryProtocol.decode(hex(it))) }

        listOf(
            "0104706565720220111111111111111111111111111111111111111111111111111111111111111103202222222222222222222222222222222222222222222222222222222222222222",
            "01047065657202201111111111111111111111111111111111111111111111111111111111111111032022222222222222222222222222222222222222222222222222222222222222220408010203040506070805020081",
        ).forEach { assertNotNull(IdentityAnnouncement.decode(hex(it))) }
    }

    private fun hex(value: String): ByteArray = value.chunked(2).map { it.toInt(16).toByte() }.toByteArray()
}
